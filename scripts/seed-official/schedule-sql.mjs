#!/usr/bin/env node
// Writes the daily-sound schedule as one SQL statement for the Supabase SQL editor.
//
//   node scripts/seed-official/schedule-sql.mjs [--start-date YYYY-MM-DD] [--out file.sql]
//
// It needs the daily-sound migration (PR #112, `public.schedule_daily_sound`). Posts are found
// by caption on @handstrudel, so it can be run any time after they are published. Days in the
// past, posts not published yet, and days that already have a scheduled sound are skipped.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadManifest, parseArgs, sqlString } from './lib.mjs';

export function scheduleSql({ manifest, startDate }) {
  const daily = manifest.posts.filter((p) => p.daily).sort((a, b) => a.daily.day - b.daily.day);
  const rows = daily.map((p) =>
    `    (${p.daily.day - 1}, ${sqlString(p.caption)},\n     ${sqlString(p.daily.title)}, ${sqlString(p.daily.note)})`);
  return `-- Daily-sound schedule for @${manifest.account.username}'s seed posts (${daily.length} days).
-- Generated by scripts/seed-official/schedule-sql.mjs from posts.json. Needs PR #112's migration.
-- Change the start day (a UTC date) on the next line if needed, then run the whole statement.
with settings as (select date '${startDate}' as start_day),
plan(day_offset, caption, title, note) as (
  values
${rows.join(',\n')}
),
targets as (
  select s.start_day + plan.day_offset as day, v.id as video_id, plan.title, plan.note
  from plan cross join settings s
  join public.profiles p on p.username = ${sqlString(manifest.account.username)}
  join public.videos v on v.user_id = p.id and v.caption = plan.caption and not v.hidden
  where s.start_day + plan.day_offset >= (now() at time zone 'utc')::date
    and not exists (select 1 from public.daily_sounds d where d.day = s.start_day + plan.day_offset and d.source = 'scheduled')
)
select t.day, t.title, (public.schedule_daily_sound(t.day, t.video_id, t.title, t.note)).video_id as scheduled_video
from targets t
order by t.day;
`;
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const args = parseArgs(process.argv.slice(2));
  const startDate = args['start-date'] ?? '2026-12-01';
  if (!/^\d{4}-\d{2}-\d{2}$/.test(startDate)) throw new Error('--start-date must be YYYY-MM-DD');
  const out = args.out ?? path.join(path.dirname(fileURLToPath(import.meta.url)), 'schedule.sql');
  fs.writeFileSync(out, scheduleSql({ manifest: loadManifest(), startDate }));
  console.log(`wrote ${out}`);
}
